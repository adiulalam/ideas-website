-- ---------------------------------------------------------------------------
-- Baseline schema for Ideal Ideas.
--
-- Reconstructed from the queries in the original (2022) code so that a local
-- database matches production as closely as possible: the legacy 32-character
-- MD5 password column, MyISAM tables and the same mix of utf8mb3 / latin1
-- character sets as the production tables (checked November 2026). The
-- migrations bring all of that up to date, so a fresh dev database exercises
-- exactly the upgrade path production went through. Production was created by
-- hand and may still differ in column types, indexes and constraints.
--
-- Do NOT edit this file to change the schema. Add a migration in
-- database/migrations/ instead; migrations run automatically on container
-- start (see docker/entrypoint.sh and bin/migrate.php).
-- ---------------------------------------------------------------------------

SET NAMES utf8mb4;

CREATE TABLE Author (
    Author_ID    INT UNSIGNED NOT NULL AUTO_INCREMENT,
    Name         VARCHAR(255) NOT NULL,
    Email        VARCHAR(255) NOT NULL,
    Password     CHAR(32)     NOT NULL,
    Author_Image VARCHAR(255) NULL,
    LoginTime    DATETIME     NULL,
    PRIMARY KEY (Author_ID),
    UNIQUE KEY uq_author_email (Email)
) ENGINE=MyISAM DEFAULT CHARSET=utf8mb3 COLLATE=utf8mb3_general_ci;

CREATE TABLE Role (
    ID          VARCHAR(64)  NOT NULL,
    Description VARCHAR(255) NOT NULL DEFAULT '',
    PRIMARY KEY (ID)
) ENGINE=MyISAM DEFAULT CHARSET=utf8mb3 COLLATE=utf8mb3_general_ci;

CREATE TABLE AuthorRole (
    AuthorID INT UNSIGNED NOT NULL,
    RoleID   VARCHAR(64)  NOT NULL,
    PRIMARY KEY (AuthorID, RoleID)
) ENGINE=MyISAM DEFAULT CHARSET=utf8mb3 COLLATE=utf8mb3_general_ci;

CREATE TABLE Idea (
    ID       INT UNSIGNED NOT NULL AUTO_INCREMENT,
    IdeaText TEXT         NOT NULL,
    IdeaDate DATE         NOT NULL,
    Image    VARCHAR(255) NOT NULL DEFAULT '',
    Document VARCHAR(255) NULL,
    AuthorID INT UNSIGNED NOT NULL,
    PRIMARY KEY (ID),
    KEY idx_idea_author (AuthorID),
    KEY idx_idea_date (IdeaDate)
) ENGINE=MyISAM DEFAULT CHARSET=utf8mb3 COLLATE=utf8mb3_bin;

CREATE TABLE Category (
    ID    INT UNSIGNED NOT NULL AUTO_INCREMENT,
    Name  VARCHAR(255) NOT NULL,
    Image VARCHAR(255) NULL,
    PRIMARY KEY (ID)
) ENGINE=MyISAM DEFAULT CHARSET=utf8mb3 COLLATE=utf8mb3_general_ci;

CREATE TABLE IdeaCategory (
    IdeaID     INT UNSIGNED NOT NULL,
    CategoryID INT UNSIGNED NOT NULL,
    PRIMARY KEY (IdeaID, CategoryID),
    KEY idx_ideacategory_category (CategoryID)
) ENGINE=MyISAM DEFAULT CHARSET=utf8mb3 COLLATE=utf8mb3_general_ci;

CREATE TABLE Department (
    ID   INT UNSIGNED NOT NULL AUTO_INCREMENT,
    Name VARCHAR(255) NOT NULL,
    PRIMARY KEY (ID)
) ENGINE=MyISAM DEFAULT CHARSET=latin1 COLLATE=latin1_swedish_ci;

CREATE TABLE IdeaDepartment (
    IdeaID       INT UNSIGNED NOT NULL,
    DepartmentID INT UNSIGNED NOT NULL,
    PRIMARY KEY (IdeaID, DepartmentID)
) ENGINE=MyISAM DEFAULT CHARSET=latin1 COLLATE=latin1_swedish_ci;

CREATE TABLE Vote (
    IdeaID     INT UNSIGNED NOT NULL,
    AuthorID   INT UNSIGNED NOT NULL,
    VoteNumber TINYINT      NOT NULL,
    PRIMARY KEY (IdeaID, AuthorID),
    KEY idx_vote_author (AuthorID)
) ENGINE=MyISAM DEFAULT CHARSET=latin1 COLLATE=latin1_swedish_ci;

CREATE TABLE Comment (
    CommentID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    Comment   TEXT         NOT NULL,
    Time      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    IdeaID    INT UNSIGNED NOT NULL,
    AuthorID  INT UNSIGNED NOT NULL,
    PRIMARY KEY (CommentID),
    KEY idx_comment_idea (IdeaID),
    KEY idx_comment_author (AuthorID)
) ENGINE=MyISAM DEFAULT CHARSET=latin1 COLLATE=latin1_swedish_ci;
